import { existsSync } from "node:fs"
import { mkdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"

import {
  DEFAULT_STYLE,
  loadStyleData,
  STYLE_NAMES,
  styleSheet,
  TWIN_BASES,
} from "./lib/styles.mjs"

const ROOT = path.resolve(import.meta.dirname, "..")
const OUTPUT = path.join(ROOT, "styles/generated")
const DATA = path.join(ROOT, "registry/styles.json")
const HEADER = "/* Generated by scripts/build-styles.mjs. Do not edit. */\n"

const check = process.argv.includes("--check")
const stale = []

await mkdir(OUTPUT, { recursive: true })

const sheets = [
  ...STYLE_NAMES.map((name) => [`style-${name}.css`, name, undefined]),
  ...TWIN_BASES.map((base) => [
    `style-${DEFAULT_STYLE}-${base}.css`,
    DEFAULT_STYLE,
    base,
  ]),
]

const outputs = [[DATA, `${JSON.stringify(await loadStyleData())}\n`]]
for (const [fileName, name, base] of sheets) {
  outputs.push([
    path.join(OUTPUT, fileName),
    `${HEADER}${(await styleSheet(name, base)).trim()}\n`,
  ])
}

for (const [file, content] of outputs) {
  const current = existsSync(file) ? await readFile(file, "utf8") : ""
  if (current === content) continue
  if (check) stale.push(path.relative(ROOT, file))
  else await writeFile(file, content)
}

if (stale.length > 0) {
  console.error(
    `Out of date: ${stale.join(", ")}. Run pnpm --filter @esuiss/web styles`
  )
  process.exit(1)
}
