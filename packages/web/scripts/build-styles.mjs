import { existsSync } from "node:fs"
import { mkdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"

import { STYLE_NAMES, styleSheet } from "./lib/styles.mjs"

const ROOT = path.resolve(import.meta.dirname, "..")
const OUTPUT = path.join(ROOT, "styles/generated")
const HEADER = "/* Generated by scripts/build-styles.mjs. Do not edit. */\n"

const check = process.argv.includes("--check")
const stale = []

await mkdir(OUTPUT, { recursive: true })

for (const name of STYLE_NAMES) {
  const file = path.join(OUTPUT, `style-${name}.css`)
  const content = `${HEADER}${(await styleSheet(name)).trim()}\n`
  const current = existsSync(file) ? await readFile(file, "utf8") : ""
  if (current === content) continue
  if (check) stale.push(path.relative(ROOT, file))
  else await writeFile(file, content)
}

if (stale.length > 0) {
  console.error(
    `Out of date: ${stale.join(", ")}. Run pnpm --filter @esuiss/web styles`
  )
  process.exit(1)
}
