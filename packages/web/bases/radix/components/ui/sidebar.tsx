function SidebarMenuSkeleton({
  className,
  showIcon = false,
  ...props
}: React.ComponentProps<"div"> & {
  showIcon?: boolean
}) {
  const id = React.useId()
  const width = `${
    50 +
    (Array.from(id).reduce(
      (hash, character) => (hash * 31 + character.charCodeAt(0)) % 9973,
      7
    ) %
      40)
  }%`

  return (
    <div
      data-slot="sidebar-menu-skeleton"
      className={cn("cn-sidebar-menu-skeleton flex items-center", className)}
      {...props}
    >
      {showIcon && <Skeleton className="size-4 rounded-sm bg-secondary" />}
      <Skeleton
        className="h-4 max-w-(--skeleton-width) flex-1 bg-secondary"
        style={
          {
            "--skeleton-width": width,
          } as React.CSSProperties
        }
      />
    </div>
  )
}

