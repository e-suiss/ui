import { HugeiconsIcon, type IconSvgElement } from "@hugeicons/react-native"
import type * as React from "react"
import type { StyleProp, TextStyle, ViewStyle } from "react-native"

type IconWeight = "thin" | "light" | "regular" | "bold" | "fill" | "duotone"

interface IconProps {
  color?: string
  duotoneColor?: string
  duotoneOpacity?: number
  mirrored?: boolean
  size?: string | number
  style?: StyleProp<ViewStyle | Omit<TextStyle, "cursor">>
  testID?: string
  title?: string
  titleId?: string
  weight?: IconWeight
}

type Icon = React.FC<IconProps>

const SCALE: Record<IconWeight, number> = {
  thin: 0.5,
  light: 0.75,
  regular: 1,
  bold: 1.25,
  fill: 1,
  duotone: 1,
}

function mirror(style: IconProps["style"], mirrored?: boolean) {
  return (
    mirrored ? [{ transform: [{ scaleX: -1 }] }, style] : style
  ) as StyleProp<ViewStyle>
}

function icon(data: IconSvgElement): Icon {
  return function HugeiconsAdapter({
    color = "#000",
    mirrored,
    size = 24,
    style,
    testID,
    weight = "regular",
  }: IconProps) {
    return (
      <HugeiconsIcon
        icon={data}
        color={color}
        size={size}
        strokeWidth={1.5 * SCALE[weight]}
        style={mirror(style, mirrored)}
        testID={testID}
      />
    )
  }
}

